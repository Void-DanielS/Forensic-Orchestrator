"""Orchestrated multi-agent investigation: a learned orchestrator coordinates intelligent agents in rounds.

    python main.py orchestrate --case <id> [--k 100] [--batch 25] [--no-feedback] [--no-vlm]

Agents
------
* **Orchestrator** (the investigation planner, ``src/ml/planner.py``): ranks every file of the case from five
  modalities, keeps a shared *blackboard* of verified leads, and in each round chooses which files to read next and
  which agent reads them. From round 2 on the ranking combines the planner's prediction with the leads the agents have
  verified so far (files whose content contains a verified name, account, e-mail or URL move up):
  ``score = logit(p) + BETA * log(1 + hits)``; ``BETA`` is fixed a priori, not tuned on any case.
* **AnalystAgent** (local LLM, ``src/agents/analyst_agent.py``): reads non-image files given the brief and the
  current leads, quotes verbatim what matters and proposes new leads; calls the identifier-extraction tool.
* **Image agent** = ImageTriageAgent (Jev-MM: pixels + metadata + OCR text) + MultimodalVisionAgent (Qwen2.5-VL):
  Jev-MM triages every dispatched image and the VLM reads the most likely user-generated ones; text the VLM or OCR
  reads is evidence only when corroborated by a case artifact.

Safeguard: every agent statement passes the HeuristicVerificationEngine. Only VERIFIED statements enter the evidence
or the blackboard; REJECTED ones (e.g. a quote the LLM invented) are counted as hallucinations caught.

``feedback=False`` is the ablation: the same agents and budget, but the files are chosen once by the planner alone
(no blackboard, no re-ranking, no leads in the analyst's prompt). ``tools=False``: the analyst's deterministic
identifier-extraction tool is off (only what the LLM chooses to quote can be evidence). ``ranker="lr"``: control, the
files are the top K of the logistic-regression baseline (metadata only), read once by the same agents.

The evaluation is split by the source of each VERIFIED finding: LLM quotes, the extraction tool, the image agent,
and the union, so the LLM agent's own contribution is visible.
"""
from __future__ import annotations

import json
import math
import os
import re
import time
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

import numpy as np

from src.cases.registry import CASES
from src.pipeline.solve import evaluate_against_key, is_image, plan, planner_for

BETA = 2.0                 # weight of verified-lead hits in the re-ranking (fixed a priori)
VLM_PER_ROUND = 3          # images the VLM reads per round (the most likely user-generated by Jev-MM)
MAX_LEADS = 40
# vendor / infrastructure identifiers present on every machine: never leads
_GENERIC = re.compile(r"(microsoft|google|apple|mozilla|w3|adobe|android|schemas|xmlsoap|verisign|digicert|"
                      r"windowsupdate|msn|openxmlformats|purl|ietf|xml)\.(com|org|net)\b", re.I)


def rerank(p: np.ndarray, rows: list[dict], leads: list[str], done: set[int]) -> np.ndarray:
    logit = np.log(np.clip(p, 1e-6, 1 - 1e-6) / np.clip(1 - p, 1e-6, 1))
    if leads:
        low = [l.lower() for l in leads]
        hits = np.array([sum(1 for l in low if l in r["snippet"].lower()) if i not in done else 0
                         for i, r in enumerate(rows)])
        logit = logit + BETA * np.log1p(hits)
    logit[list(done)] = -np.inf
    return logit


def _image_leads(findings) -> list[str]:
    from src.agents.reader_agent import EMAIL, URL

    out = []
    for f in findings:
        if f.status.value != "verified" or not f.observed_text:
            continue
        b = f.observed_text.encode("utf-8", "ignore")
        out += [m.group().decode("ascii", "ignore") for rx in (EMAIL, URL) for m in rx.finditer(b)]
    return out


def source(f) -> str:
    """Which agent produced a finding: 'llm' (analyst quotes), 'tool' (analyst extraction tool) or 'image'."""
    if f.agent == "AnalystAgent":
        return "tool" if f.category.startswith("analyst.tool") else "llm"
    return "image"


def split_evaluation(case, verified: list[dict]) -> dict | None:
    """Answer-key identifiers in VERIFIED findings, per source and in the union (``llm_only``: found by an LLM quote
    and by no other source)."""
    from src.eval.scoring import found_entities, key_entities

    ents = key_entities(case.dir, case.summary)
    if not ents:
        return None
    got = {s: found_entities(ents, [f for f in verified if f["_source"] == s]) for s in ("llm", "tool", "image")}
    union = set().union(*got.values())
    return {"key_identifiers": len(ents), **{s: len(v) for s, v in got.items()}, "union": len(union),
            "llm_only": len(got["llm"] - got["tool"] - got["image"])}


def investigate(case_id: str, k: int = 100, batch: int = 25, feedback: bool = True, vlm: bool = True,
                checkpoint: Path | None = None, quiet: bool = False, tools: bool = True,
                ranker: str = "planner") -> dict:
    os.environ.setdefault("HF_HUB_OFFLINE", "1")
    from src.agents.analyst_agent import AnalystAgent
    from src.agents.llm import LocalLLM
    from src.agents.mm_agent import ImageTriageAgent
    from src.agents.trace import Tracer
    from src.agents.vision_agent import MultimodalVisionAgent
    from src.bridge.forensic_bridge import ForensicBridge
    from src.ml.planner_dataset import brief_text

    t_start = time.perf_counter()
    case = CASES[case_id]
    planner, ck = planner_for(case_id, checkpoint)
    rows, p, _, meta = plan(case, planner, quiet, return_meta=True)
    if ranker == "lr":
        from src.pipeline.solve import lr_scores

        p = 1 / (1 + np.exp(-lr_scores(case_id, meta)))
        feedback, ck = False, "logistic regression (metadata), other solved cases"
    brief = brief_text(case)
    mode = "lr" if ranker == "lr" else ("orch" if feedback else "orch-nofb") + ("" if tools else "-notool")
    run_id = datetime.now().strftime("%Y%m%d-%H%M%S") + "-" + mode
    run_dir = case.dir / "workspace" / "runs" / run_id
    run_dir.mkdir(parents=True, exist_ok=True)
    tracer = Tracer(run_dir, {"run_id": run_id, "case_id": case_id, "k": k, "batch": batch, "feedback": feedback,
                              "tools": tools, "ranker": ranker, "planner": ck})
    llm = LocalLLM()
    manifests, names, bridges, text_index = {}, {}, {}, {}
    for eid in {r["evidence_id"] for r in rows}:
        ev = case.dir / "evidence" / eid
        manifests[eid] = json.loads((ev / "MANIFEST.json").read_text(encoding="utf-8"))
        names[eid] = {f["path"][3:]: (f.get("original_path") or f["path"]) for f in manifests[eid]["files"]
                      if f["path"].startswith("fs/")}
        bridges[eid] = ForensicBridge(ev / "fs")

    leads: list[str] = []
    done: set[int] = set()
    findings, rounds = [], []
    n_rounds = math.ceil(min(k, len(rows)) / batch) if feedback else 1
    try:
        for rnd in range(1, n_rounds + 1):
            take = min(batch if feedback else k, k - len(done), len(rows) - len(done))
            if take <= 0:
                break
            score = rerank(p, rows, leads if feedback else [], done)
            pick = [int(i) for i in np.argsort(-score, kind="stable")[:take]]
            done |= set(pick)
            work: dict[str, dict[str, list[str]]] = defaultdict(lambda: {"image": [], "text": []})
            for i in pick:
                r = rows[i]
                rel = r["path"][3:] if r["path"].startswith("fs/") else r["path"]
                work[r["evidence_id"]]["image" if is_image(r) else "text"].append(rel)
            tracer.emit("dispatch", round=rnd, files=len(pick), leads=leads[:MAX_LEADS],
                        to={"AnalystAgent": sum(len(w["text"]) for w in work.values()),
                            "ImageAgent": sum(len(w["image"]) for w in work.values())})
            new_leads: list[str] = []
            rf = []
            for eid, w in work.items():
                if w["text"]:
                    ag = AnalystAgent(bridges[eid], names=names[eid], brief=brief, leads=leads if feedback else [],
                                      llm=llm, tools=tools, tracer=tracer, evidence_id=eid, run_id=run_id)
                    try:
                        rep = ag.run(w["text"], output_dir=run_dir)
                        rf += rep.findings
                        new_leads += ag.verified_leads(rep.findings)
                    finally:
                        ag.close()
                if w["image"]:
                    tri = ImageTriageAgent(bridges[eid], manifest=manifests[eid], tracer=tracer, evidence_id=eid,
                                           run_id=run_id)
                    try:
                        rep = tri.run(w["image"], output_dir=run_dir)
                        rf += rep.findings
                        queue = [rel for rel, _ in tri.rank()][:VLM_PER_ROUND]
                    finally:
                        tri.release()
                        tri.close()
                    if vlm and queue:
                        va = MultimodalVisionAgent(bridges[eid], text_index=text_index.get(eid), tracer=tracer,
                                                   evidence_id=eid, run_id=run_id)
                        try:
                            rep = va.run(queue, output_dir=run_dir)
                            text_index[eid] = va.text_index
                            rf += rep.findings
                            new_leads += _image_leads(rep.findings)
                        finally:
                            va.release(keep_models=True)
                            va.close()
            findings += rf
            fresh = [l for l in dict.fromkeys(new_leads) if l not in leads and not _GENERIC.search(l)]
            leads = (leads + fresh)[:MAX_LEADS]
            st = Counter(f.status.value for f in rf)
            rounds.append({"round": rnd, "files": len(pick), "status": dict(st), "new_leads": fresh[:15]})
            tracer.emit("blackboard", round=rnd, new_leads=fresh, leads=len(leads), status=dict(st))
            if not quiet:
                print(f"[orchestrate] {case_id} round {rnd}: {len(pick)} files, {dict(st)}, +{len(fresh)} leads",
                      flush=True)
    finally:
        for b in bridges.values():
            b.close()
    status = Counter(f.status.value for f in findings)
    verified = [{**f.model_dump(mode="json"), "_source": source(f)} for f in findings if f.status.value == "verified"]
    llm_quotes = [f for f in findings if f.agent == "AnalystAgent" and not f.category.startswith("analyst.tool")]
    hallucinations = {"llm_quotes": len(llm_quotes),
                      "rejected": sum(1 for f in llm_quotes if f.status.value == "rejected")}
    evaluation = evaluate_against_key(case, verified)
    if evaluation is not None:
        evaluation["by_source"] = split_evaluation(case, verified)
    out = {"run_id": run_id, "case": case_id, "files": len(rows), "read": len(done), "k": k, "feedback": feedback,
           "tools": tools, "ranker": ranker,
           "status": dict(status), "by_agent": dict(Counter(f"{f.agent}:{f.status.value}" for f in findings)),
           "hallucinations_caught": hallucinations, "rounds": rounds, "leads": leads, "evaluation": evaluation,
           "planner": ck, "seconds": round(time.perf_counter() - t_start, 1)}
    tracer.finish("done", counts=dict(status), evaluation=evaluation)
    (run_dir / "orchestrate.json").write_text(json.dumps(out, indent=1, default=str), encoding="utf-8")
    write_report(case, run_dir, out, findings)
    if not quiet:
        print(f"[orchestrate] {case_id}: {dict(status)}; LLM quotes rejected {hallucinations}; "
              f"evaluation {evaluation and {k_: evaluation.get(k_) for k_ in ('found', 'key_identifiers')}}", flush=True)
    return out


def write_report(case, run_dir: Path, out: dict, findings) -> Path:
    lines = [f"# Orchestrated investigation: {case.case_id}", "",
             f"Run `{out['run_id']}`; planner `{out['planner']}`; {out['read']} of {out['files']:,} files read; "
             f"feedback {'on' if out['feedback'] else 'off'}; {out['seconds']} s.", "",
             "## Rounds (orchestrator blackboard)", "", "| round | files | status | new verified leads |",
             "|---|---|---|---|"]
    for r in out["rounds"]:
        lines.append(f"| {r['round']} | {r['files']} | {r['status']} | {', '.join(r['new_leads'][:8])} |")
    lines += ["", f"Hallucinations caught (LLM quotes not found in the cited file): "
                  f"{out['hallucinations_caught']['rejected']} of {out['hallucinations_caught']['llm_quotes']}", "",
              "## Verified evidence (LLM quotes and corroborated image text)", ""]
    for f in findings:
        if f.status.value == "verified" and (f.category.startswith("analyst.") and not f.category.startswith(
                "analyst.tool") or f.observed_text):
            lines.append(f"* `{f.category}` {f.claim}")
    path = run_dir / "orchestrate_report.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
