"""iOS system databases: Messages, AddressBook, CallHistory, KnowledgeC, Notes, Calendar, Photos."""
from src.agents.parsers.base import Col, Lookup, TableSpec

_FROM_ME = {0: "received from", 1: "sent to"}

SPECS = [
    TableSpec("imessage.message", r"(^|/)sms\.db$", ("message",),
              (Col("text", ("text",)), Col("date", ("date",), "cocoa_auto"), Col("is_from_me", ("is_from_me",)),
               Col("service", ("service",)), Col("handle_id", ("handle_id",), cite=False),
               Col("date_read", ("date_read",), "cocoa_auto", cite=False)),
              require=("text", "date"), text=("text",), labels={"is_from_me": _FROM_ME},
              lookups=(Lookup("handle", ("handle",), ("ROWID",), ("id",), "handle_id"),),
              claim="{service} {is_from_me_label} {handle} at {date_utc}: {text}",
              description="iOS Messages (sms.db, table message + handle)"),
    TableSpec("contact.person", r"(^|/)AddressBook\.sqlitedb$", ("ABPerson",),
              (Col("first", ("First",)), Col("last", ("Last",)), Col("organization", ("Organization",)),
               Col("created", ("CreationDate",), "cocoa_s")),
              require=("first",), text=("first", "last", "organization"),
              claim="Contact: {first} {last} {organization}",
              description="iOS contacts (AddressBook.sqlitedb, table ABPerson)"),
    TableSpec("contact.value", r"(^|/)AddressBook\.sqlitedb$", ("ABMultiValue",),
              (Col("value", ("value",)), Col("record_id", ("record_id",), cite=False),
               Col("property", ("property",), cite=False)),
              require=("value", "record_id"), text=("value",),
              lookups=(Lookup("first", ("ABPerson",), ("ROWID",), ("First",), "record_id"),
                       Lookup("last", ("ABPerson",), ("ROWID",), ("Last",), "record_id")),
              claim="Contact value of {first} {last}: {value}",
              description="iOS contact phone numbers / e-mails (ABMultiValue + ABPerson)"),
    TableSpec("call.log", r"(^|/)CallHistory\.storedata$", ("ZCALLRECORD",),
              (Col("address", ("ZADDRESS",)), Col("date", ("ZDATE",), "cocoa_s"), Col("duration", ("ZDURATION",)),
               Col("originated", ("ZORIGINATED",)), Col("answered", ("ZANSWERED",)), Col("name", ("ZNAME",)),
               Col("service", ("ZSERVICE_PROVIDER",))),
              require=("date",), labels={"originated": {0: "incoming", 1: "outgoing"}},
              claim="Call {originated_label} {address} {name} at {date_utc}, {duration}s via {service}",
              description="iOS call history (CallHistory.storedata, ZCALLRECORD)"),
    TableSpec("knowledgec.event", r"(^|/)knowledgeC\.db$", ("ZOBJECT",),
              (Col("stream", ("ZSTREAMNAME",)), Col("value", ("ZVALUESTRING",)), Col("start", ("ZSTARTDATE",), "cocoa_s"),
               Col("end", ("ZENDDATE",), "cocoa_s")),
              require=("stream", "start"), text=("value",), max_rows=3000,
              where="{col:stream} IN ('/app/inFocus','/app/usage','/app/webUsage','/safari/history',"
                    "'/device/isLocked','/display/isBacklit','/app/intents','/notification/usage')",
              claim="KnowledgeC {stream}: {value} from {start_utc} to {end_utc}",
              description="iOS KnowledgeC pattern-of-life events (ZOBJECT)"),
    TableSpec("notes.note", r"(^|/)NoteStore\.sqlite$", ("ZICCLOUDSYNCINGOBJECT",),
              (Col("title", ("ZTITLE1", "ZTITLE")), Col("snippet", ("ZSNIPPET",)),
               Col("created", ("ZCREATIONDATE3", "ZCREATIONDATE1", "ZCREATIONDATE"), "cocoa_s"),
               Col("modified", ("ZMODIFICATIONDATE1", "ZMODIFICATIONDATE"), "cocoa_s")),
              require=("title",), text=("title",),
              claim="Note '{title}' created {created_utc}: {snippet}",
              description="iOS Notes (NoteStore.sqlite)"),
    TableSpec("calendar.event", r"(^|/)Calendar\.sqlitedb$", ("CalendarItem",),
              (Col("title", ("summary",)), Col("start", ("start_date",), "cocoa_s"), Col("end", ("end_date",), "cocoa_s"),
               Col("description", ("description",))),
              require=("title",), text=("title",),
              claim="Calendar event '{title}' starting {start_utc}",
              description="iOS calendar (Calendar.sqlitedb, CalendarItem)"),
    TableSpec("photos.asset", r"(^|/)Photos\.sqlite$", ("ZASSET", "ZGENERICASSET"),
              (Col("filename", ("ZFILENAME",)), Col("directory", ("ZDIRECTORY",)),
               Col("created", ("ZDATECREATED",), "cocoa_s"), Col("latitude", ("ZLATITUDE",)),
               Col("longitude", ("ZLONGITUDE",))),
              require=("filename", "latitude", "longitude"), text=("filename",),
              where="{col:latitude} BETWEEN -90 AND 90 AND {col:latitude} != 0",
              claim="Photo {directory}/{filename} taken {created_utc} at {latitude},{longitude}",
              description="iOS Photos library assets with location (Photos.sqlite)"),
]
